import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile, mkdtemp, mkdir, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';

const workflow = await readFile(new URL('../../.github/workflows/pages.yml', import.meta.url), 'utf8');
const step = workflow.slice(workflow.indexOf('- name: Replace generated publication'));
const runStart = step.indexOf('run: |\n');
const replaceStart = step.indexOf('          rsync -a');
assert.ok(runStart >= 0 && replaceStart > runStart, 'Find the actual pre-publication checks, before any replacement.');
const checks = step.slice(runStart + 'run: |\n'.length, replaceStart).replace(/^          /gm, '');
const heading = '# By-Indies-Pages';
const description = 'Independent projects and the people who make them. Generated from Sponsored by Indies.';
const marker = '<!-- Generated by Sponsored-by-Indies. Edit the source repository. -->';

for (const [scenario, readme, extra, domain, allowed] of [
  ['generated publication', marker + '\n# By Indies', 'index.html', 'byindies.com', true],
  ['empty starter', heading, null, 'byindies.com', true],
  ['described starter', heading + '\n\n' + description, null, 'byindies.com', true],
  ['GitHub-created starter', heading + '\n' + description, null, 'byindies.com', true],
  ['unrelated README', '# Another project', null, 'byindies.com', false],
  ['unrelated content under the same title', heading + '\n\nA different application.', null, 'byindies.com', false],
  ['starter with source files', heading, 'application.swift', 'byindies.com', false],
  ['another domain', marker, 'index.html', 'another.example.org', false]
]) {
  test(`publication destination checks: ${scenario}`, async () => {
    const root = await mkdtemp(join(tmpdir(), 'by-indies-publication-'));
    try {
      await mkdir(join(root, 'publication'));
      await mkdir(join(root, 'pages'));
      await writeFile(join(root, 'publication/index.html'), 'Generated site');
      await writeFile(join(root, 'publication/CNAME'), 'byindies.com\n');
      await writeFile(join(root, 'pages/README.md'), readme + '\n');
      await writeFile(join(root, 'pages/CNAME'), domain + '\n');
      if (extra) await writeFile(join(root, 'pages', extra), 'Existing content');
      for (const args of [['init', '-q'], ['add', '--all']]) {
        const git = spawnSync('git', args, { cwd: join(root, 'pages'), encoding: 'utf8' });
        assert.equal(git.status, 0, git.stderr);
      }
      // Execute only the guard from the workflow; no files are replaced or pushed.
      const result = spawnSync('/bin/bash', ['-e', '-o', 'pipefail', '-c', checks], {
        cwd: root, env: { ...process.env, TARGET_REPOSITORY: 'dadederk/By-Indies-Pages' }, encoding: 'utf8'
      });
      assert.equal(result.status === 0, allowed, result.stderr);
      assert.equal(await readFile(join(root, 'pages/README.md'), 'utf8'), readme + '\n');
    } finally {
      await rm(root, { recursive: true, force: true });
    }
  });
}
