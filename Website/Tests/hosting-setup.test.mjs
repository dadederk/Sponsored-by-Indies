import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp, writeFile, readFile, rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join, resolve, dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';

const script = resolve(dirname(fileURLToPath(import.meta.url)), '../../Scripts/SetupByIndiesHosting.swift');
const source = 'dadederk/Sponsored-by-Indies';
const target = 'dadederk/By-Indies-Pages';

async function fixture(scenario, check) {
  const root = await mkdtemp(join(tmpdir(), 'by-indies-hosting-test-'));
  const stateFile = join(root, 'state.json');
  await writeFile(stateFile, JSON.stringify({scenario, calls:[], repository:false, pages:scenario === 'foreign-domain',
    cname:scenario === 'foreign-domain' ? 'another.example.org' : undefined, https:false}));
  // A fake CLI isolates setup decisions from live GitHub, credentials and DNS.
  await writeFile(join(root, 'gh'), `#!/usr/bin/env node
const fs = require('node:fs');
const file = process.env.BY_INDIES_TEST_STATE;
const state = JSON.parse(fs.readFileSync(file, 'utf8'));
const args = process.argv.slice(2);
const method = args.includes('--method') ? args[args.indexOf('--method') + 1] : 'GET';
const body = args.includes('--input') ? JSON.parse(fs.readFileSync(args[args.indexOf('--input') + 1], 'utf8')) : null;
state.calls.push({args, method, body});
function respond(value) {fs.writeFileSync(file, JSON.stringify(state)); process.stdout.write(JSON.stringify(value));}
function fail(message) {fs.writeFileSync(file, JSON.stringify(state)); process.stderr.write(message); process.exit(1);}
if (args[0] === 'repo' && args[1] === 'create') {state.repository = true; respond({});}
else if (args[0] === 'secret' && args[1] === 'list') respond(state.scenario === 'missing-secret' ? [] : [{name:'BY_INDIES_PAGES_TOKEN'}]);
else if (args[0] === 'variable') respond({});
else if (args[0] !== 'api') fail('Unexpected CLI command');
else {
  const endpoint = args[1];
  if (endpoint === 'repos/${source}') {
    if (state.scenario === 'timeout') setTimeout(() => respond({permissions:{admin:true}}), 10_000);
    else respond({permissions:{admin:true}});
  }
  else if (endpoint === 'repos/${source}/pages') respond({cname:'sponsored.byindies.com'});
  else if (endpoint === 'repos/${target}') {
    if (state.scenario === 'offline') fail('error connecting to api.github.com');
    if (state.scenario === 'forbidden') fail('gh: Resource not accessible (HTTP 403)');
    if (method === 'GET' && state.scenario === 'new' && !state.repository) fail('gh: Not Found (HTTP 404)');
    respond({private:false,permissions:{admin:true},default_branch:'main'});
  } else if (endpoint === 'repos/${target}/contents') respond(state.scenario.startsWith('starter') ? [{name:'README.md'}] : [{name:'README.md'},{name:'index.html'}]);
  else if (endpoint === 'repos/${target}/contents/README.md') respond({content:Buffer.from(
    ['unrelated', 'starter-unrelated'].includes(state.scenario) ? 'Another project' : state.scenario === 'starter' ? '# By-Indies-Pages\\n' : state.scenario === 'starter-described' ? '# By-Indies-Pages\\nIndependent projects and the people who make them. Generated from Sponsored by Indies.\\n' : '<!-- Generated by Sponsored-by-Indies. Edit the source repository. -->').toString('base64')});
  else if (endpoint === 'repos/${target}/pages') {
    if (method === 'GET' && !state.pages) fail('gh: Not Found (HTTP 404)');
    if (method === 'POST') state.pages = true;
    if (body?.cname) state.cname = body.cname;
    if (body?.https_enforced) state.https = true;
    respond({cname:state.cname,https_enforced:state.https,https_certificate:{state:state.scenario === 'certificate-ready' ? 'approved' : 'new'}});
  } else fail('Unexpected API endpoint: ' + endpoint);
}
`, {mode:0o755});
  const run = args => spawnSync('swift', [script, ...args], {
    env:{...process.env, PATH:`${root}:${process.env.PATH}`, BY_INDIES_TEST_STATE:stateFile,
      CLANG_MODULE_CACHE_PATH:join(root, 'clang-cache'), SWIFT_MODULECACHE_PATH:join(root, 'swift-cache')},
    encoding:'utf8', timeout:30_000
  });
  const state = async () => JSON.parse(await readFile(stateFile, 'utf8'));
  try {await check(run, state);} finally {await rm(root, {recursive:true, force:true});}
}

test('hosting setup creates the output repository and is safe to rerun without replacing its secret', async () => {
  await fixture('new', async (run, readState) => {
    for (let attempt = 0; attempt < 2; attempt++) {
      const result = run(['--apply']);
      assert.equal(result.status, 0, result.stderr);
    }
    const {calls} = await readState();
    assert.equal(calls.filter(call => call.args[0] === 'repo').length, 1);
    assert.equal(calls.filter(call => call.method === 'POST' && call.args[1].endsWith('/pages')).length, 1);
    assert.ok(calls.some(call => call.body?.cname === 'byindies.com' && call.body?.source?.branch === 'main'));
    assert.equal(calls.filter(call => call.args[0] === 'secret' && call.args[1] === 'set').length, 0);
    assert.ok(calls.some(call => call.args[0] === 'variable' && call.args.includes(target)));
    assert.ok(!calls.some(call => call.method !== 'GET' && call.args[1] === `repos/${source}/pages`), 'preserve the sponsored site');
  });
});

for (const scenario of ['offline', 'forbidden', 'unrelated', 'starter-unrelated', 'foreign-domain']) {
  test(`hosting setup stops on ${scenario} instead of creating or overwriting another repository`, async () => {
    await fixture(scenario, async (run, readState) => {
      const result = run(['--apply']);
      assert.notEqual(result.status, 0);
      assert.match(result.stderr, scenario === 'offline' ? /error connecting to api.github.com/ : scenario === 'forbidden' ? /HTTP 403/
        : scenario === 'foreign-domain' ? /already serves another domain/ : /destination contains another project/);
      const {calls} = await readState();
      assert.ok(!calls.some(call => call.args[0] === 'repo' || call.method !== 'GET'));
      assert.ok(!calls.some(call => call.args[0] === 'variable'));
    });
  });
}

for (const scenario of ['starter', 'starter-described']) {
  test(`hosting setup accepts the intended ${scenario} repository`, async () => {
    await fixture(scenario, async (run, readState) => {
      const result = run(['--apply']);
      assert.equal(result.status, 0, result.stderr);
      assert.ok((await readState()).calls.some(call => call.args[0] === 'variable'));
    });
  });
}

test('hosting dry run needs no GitHub access and HTTPS can be enabled after the certificate is ready', async () => {
  await fixture('certificate-ready', async (run, readState) => {
    assert.equal(run(['--dry-run']).status, 0);
    assert.equal((await readState()).calls.length, 0);
    const result = run(['--apply']);
    assert.equal(result.status, 0, result.stderr);
    assert.equal((await readState()).https, true);
    const again = run(['--enable-https']);
    assert.equal(again.status, 0, again.stderr);
    assert.match(again.stdout, /already enforced/);
  });
});

test('hosting setup leaves publishing disabled until a missing secret is stored directly', async () => {
  await fixture('missing-secret', async (run, readState) => {
    const result = run(['--apply']);
    assert.notEqual(result.status, 0);
    assert.match(result.stderr, /gh secret set BY_INDIES_PAGES_TOKEN/);
    const {calls} = await readState();
    assert.ok(!calls.some(call => call.args[0] === 'variable'));
    assert.ok(!calls.some(call => call.args[0] === 'secret' && call.args[1] === 'set'));
  });
});

test('hosting setup identifies a stalled command and stops before making changes', async () => {
  await fixture('timeout', async (run, readState) => {
    const result = run(['--apply', '--timeout', '1']);
    assert.notEqual(result.status, 0);
    assert.match(result.stdout, /Checking GitHub access/);
    assert.match(result.stderr, /timed out after 1 seconds: gh api repos\/dadederk\/Sponsored-by-Indies/);
    const {calls} = await readState();
    assert.ok(!calls.some(call => call.args[0] === 'repo' || call.method !== 'GET'));
  });
});
